package com.tripplanner.enums;

/**
 * Categories for user memory storage
 */
public enum MemoryCategory {
    PROFILE,        // Travel style, preferences
    DIETARY,        // Restrictions, allergies (PERSONAL)
    VALIDATION,     // Dismissals, preferences
    ACTIVITY,       // Preferred types, pace
    BUDGET,         // Spending patterns, flexibility
    TIMING,         // Schedule preferences, patterns
    TRANSPORT,      // Preferred modes, comfort
    MEAL,           // Dining style, importance
    INSTRUCTION,    // Explicit user commands
    HISTORY         // Past itinerary summaries
}
